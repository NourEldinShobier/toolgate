import { describe, expect, it } from 'vitest';
import { isReadOnlyBash } from '../src/readonly.js';

describe('isReadOnlyBash: every segment must only read', () => {
  const yes = [
    'ls',
    'ls -la ~/Desktop',
    'cat package.json',
    'grep -n "foo" src/*.ts | head -20',
    'rg -n TODO src',
    'wc -l src/components/Studio.jsx && grep -n saved src/components/Studio.jsx | head',
    'cd /Users/dev/project && git status --short',
    'git log --oneline -5; git diff --stat',
    'git rev-parse HEAD origin/main',
    'git branch --show-current',
    'git remote -v',
    'S=/tmp/scratch; cd $S && ls',
    'F=/Users/dev/Desktop/song.mp3; ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 $F',
    'ffprobe -hide_banner -i song.mp3 2>&1 | grep -o "Duration: [0-9:.]*"',
    'find . -name "*.jsx" | wc -l',
    'mdfind -name "song" 2>/dev/null | head -5',
    'sed -n 1,40p src/App.jsx',
    'node --check api/assemble.js',
    'tsc --noEmit',
    'npm ls --depth=0',
    'npm view @riskaverse/toolgate version',
    'tail -15 memory/notes.md',
    'echo $PATH',
    'stat -f %z out.mp4',
    'which ffmpeg; ffprobe -version 2>/dev/null | head -1 || true',
    'du -sh node_modules 2>/dev/null',
    'test -f .env && echo yes || echo no',
    // 0.17.1: operators inside quotes are not operators (the window's missed greps)
    'grep -n -i "delete.*account|deleteAccount" src/App.jsx | head -5',
    "grep -rn 'REFERRER_SIGNUP_REWARD =|REFERRED_BONUS =' api/apply-referral.js 2>/dev/null | head; grep -rln 'a|b' api src",
    'grep -rhoE "from\\(([a-z_]*(purchase|payment|order)[a-z_]*)" api src | sort | uniq -c',
    'cd ~/Desktop/site && grep -n "Product Hunt. Together|grew" -A3 src/templates/Home.tsx | head -12',
    'grep -n "credits|price|amount" api/create-checkout-session.js | head -25',
    'echo "a > b"',
  ];
  const no = [
    '',
    'rm -r src/__preview && npx vite build',
    'grep -n foo src/*.ts > out.txt',
    'cat a.txt >> b.txt',
    'ls > /tmp/x',
    'sed -i "s/a/b/" file.txt',
    'sed -n 1p x; sed -i.bak "s/a/b/" y',
    'find . -name "*.tmp" -delete',
    'find . -name "*.js" -exec node {} \\;',
    'git push origin main',
    'git add -A && git commit -m x',
    'git checkout -- .',
    'git branch -D feature',
    'git branch new-feature',
    'git stash',
    'git fetch -q',
    'npm install',
    'npm config set registry https://x',
    'node -e "require(\'fs\').writeFileSync(\'x\', \'y\')"',
    'python3 - <<EOF\nprint(1)\nEOF',
    'echo $(cat .env)',
    'cat `ls`',
    'curl -s https://example.com',
    'ls; curl -s -o /dev/null https://example.com',
    'ffmpeg -i in.mp3 out.wav',
    'ls && rm x',
    'mv a b',
    'cp a b',
    'chmod +x run.sh',
    'export X=1; ./run.sh',
    'env FOO=bar node script.js',
    'diff <(ls a) <(ls b)',
    'grep -n "foo" file.txt > out.txt',
    "grep 'x' f; rm g",
    'echo "safe" ; echo unsafe > f',
  ];
  for (const c of yes) it(`read-only: ${JSON.stringify(c)}`, () => expect(isReadOnlyBash(c)).toBe(true));
  for (const c of no) it(`not read-only: ${JSON.stringify(c)}`, () => expect(isReadOnlyBash(c)).toBe(false));
});
